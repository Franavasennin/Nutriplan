// ─────────────────────────────────────────────────────────────────────────────
// Función utilitaria para filtrar recetas por tipo de dieta
// ─────────────────────────────────────────────────────────────────────────────

export function getRecipesByDiet(dietType: string): Recipe[] {
  return RECIPES.filter(recipe =>
    recipe.tags.some(tag => tag.toLowerCase().includes(dietType.toLowerCase()))
  );
}

export function getRecipesByMealType(mealType: string): Recipe[] {
  return RECIPES.filter(recipe =>
    recipe.tags.some(tag => tag.toLowerCase() === mealType.toLowerCase())
  );
}

export function searchRecipes(query: string): Recipe[] {
  const q = query.toLowerCase();
  return RECIPES.filter(recipe =>
    recipe.title.toLowerCase().includes(q) ||
    recipe.description.toLowerCase().includes(q) ||
    recipe.tags.some(tag => tag.toLowerCase().includes(q)) ||
    recipe.ingredients.some(ing => ing.toLowerCase().includes(q))
  );
}
